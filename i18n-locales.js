  function getUiStrings(lang) {
    const out = {};
    for (const key in UI_TABLE) {
      out[key] = pick(lang, UI_TABLE[key]);
    }
    out.optViewImmersive = out.optThoughtImmersive;
    out.optViewBilingual = out.optThoughtBilingual;
    out.swarmSplitSub = (mainPct, subPct) =>
      lang === 'zh-CN'
        ? `主会话 ${mainPct}% · 子代理 ${subPct}%`
        : lang === 'zh-TW'
        ? `主工作階段 ${mainPct}% · 子代理 ${subPct}%`
        : lang === 'ja'
        ? `メイン ${mainPct}% · 子 ${subPct}%`
        : lang === 'ko'
        ? `메인 ${mainPct}% · 서브 ${subPct}%`
        : lang === 'es'
        ? `Principal ${mainPct}% · Sub ${subPct}%`
        : lang === 'fr'
        ? `Principal ${mainPct} % · Sous-agents ${subPct} %`
        : lang === 'de'
        ? `Haupt ${mainPct} % · Sub ${subPct} %`
        : `Main ${mainPct}% · Swarm ${subPct}%`;
    out.showMoreN = (n) =>
      lang === 'zh-CN'
        ? `再显示 ${n} 个`
        : lang === 'zh-TW'
        ? `再顯示 ${n} 個`
        : lang === 'ja'
        ? `さらに ${n} 件表示`
        : lang === 'ko'
        ? `${n}개 더 보기`
        : lang === 'es'
        ? `Mostrar ${n} más`
        : lang === 'fr'
        ? `Afficher ${n} de plus`
        : lang === 'de'
        ? `${n} weitere anzeigen`
        : `Show ${n} more`;
    return out;
  }

  function getRuntimeUiSlice(lang) {
    const norm = resolveLangId(lang);
    const strings = {};
    for (let i = 0; i < RUNTIME_UI_KEYS.length; i++) {
      const k = RUNTIME_UI_KEYS[i];
      if (Object.prototype.hasOwnProperty.call(UI_TABLE, k)) {
        strings[k] = pick(norm, UI_TABLE[k]);
      }
    }
    return { lang: norm, strings };
  }

