  const DICT_ROWS = [];

  function resolveLocaleBundle(lang) {
    const key = lang === 'zh-CN' || lang === 'zh-TW' || lang === 'yue' || lang === 'ja' ? lang : 'en';
    if (key === 'en') return null;
    return {
      lang: key,
      cjkLatinSpacing: key !== 'ja',
      units: null,
      dict: Object.create(null),
      rules: [],
      timeRules: [],
      sentences: [],
    };
  }

