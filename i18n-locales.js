  function resolveLocaleBundle(lang) {
    const key = lang === 'zh-CN' || lang === 'zh-TW' || lang === 'ja' || lang === 'ko' ? lang : null;
    if (!key) return null;
    return {
      lang: key,
      cjkLatinSpacing: key === 'zh-CN' || key === 'zh-TW',
      units: null,
      dict: Object.create(null),
      rules: [],
      timeRules: [],
      sentences: [],
    };
  }

